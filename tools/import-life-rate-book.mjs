// Usage: node tools/import-life-rate-book.mjs <path to life-rate-book.json>
// Reads Tatil's harvested life rate book and writes core/src/parameters/tatil-life-rates-2026-10.ts.
// Real-life-rates spec §5.2. Re-running this on a new book is the only way a rate changes.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { rateLine, rateChecksum } from "../core/src/parameters/rate-checksum.ts";

const OUT = fileURLToPath(new URL("../core/src/parameters/tatil-life-rates-2026-10.ts", import.meta.url));
const key = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k));
const ISO = /^\d{4}-\d{2}-\d{2}$/;

function fail(msg) {
  throw new Error(`import-life-rate-book: ${msg}`);
}

function toAsOf(harvestedOn) {
  let d = null;
  if (/^\d{4}-\d{2}$/.test(harvestedOn)) d = `${harvestedOn}-01`;
  else if (/^\d{4}-\d{2}-\d{2}/.test(harvestedOn)) d = harvestedOn.slice(0, 10);
  if (d === null || !ISO.test(d)) fail(`harvested_on "${harvestedOn}" is neither YYYY-MM nor starts with YYYY-MM-DD`);
  return d;
}

function slugOf(name) {
  const words = name.split(/[^A-Za-z0-9]+/).filter(Boolean);
  if (words.length === 0) fail(`variant name "${name}" has no letters or digits`);
  const camel = words
    .map((w, i) => (i === 0 ? w.toLowerCase() : w[0].toUpperCase() + w.slice(1).toLowerCase()))
    .join("");
  return /^[0-9]/.test(camel) ? `v${camel}` : camel;
}

// A JS literal, not JSON: keys unquoted where legal, so nothing in the output looks like `from "..."` to the purity guard.
const lit = (v) => {
  if (Array.isArray(v)) return `[${v.map(lit).join(", ")}]`;
  if (v !== null && typeof v === "object") {
    return `{ ${Object.entries(v).map(([k, x]) => `${key(k)}: ${lit(x)}`).join(", ")} }`;
  }
  return JSON.stringify(v);
};
const pad = (n) => "  ".repeat(n);

const bookPath = process.argv[2];
if (!bookPath) fail("usage: node tools/import-life-rate-book.mjs <path to life-rate-book.json>");
const book = JSON.parse(readFileSync(bookPath, "utf8"));

const PRODUCT_KEYS = ["term", "wholeLife", "endowment", "restAssured", "applyonCi", "lifespanGold"];
for (const k of PRODUCT_KEYS) if (!book.products?.[k]) fail(`book has no product "${k}"`);
const unknown = Object.keys(book.products).filter((k) => !PRODUCT_KEYS.includes(k));
if (unknown.length) fail(`book has products this script does not know: ${unknown.join(", ")}`);

const asOfOf = {};
const newest = PRODUCT_KEYS.map((k) => (asOfOf[k] = toAsOf(book.products[k].harvested_on))).sort().at(-1);
const sourceOf = (k, p) =>
  `Tatil ${k === "lifespanGold" ? "OIPA" : "ApplyOn"} illustration, harvested ${p.harvested_on}`;
const BOOK_SOURCE = `General-Rater-Portal rates/life/life-rate-book.json (schema ${book.schema}), newest harvest ${newest}`;

const lines = [];
let cellCount = 0;

const productBlocks = [];
for (const pk of PRODUCT_KEYS) {
  const p = book.products[pk];
  const r = (v) => `row(${lit(v)}, "verified", SRC_${pk}, ASOF_${pk})`;
  const b = [];
  const w = (n, s) => b.push(pad(n) + s);
  w(2, `${key(pk)}: {`);
  w(3, `name: ${r(p.name)},`);
  w(3, `feeAnnual: ${r(p.fee)},`);
  w(3, `minPremiumAnnual: ${r(p.min_premium ?? null)},`);
  w(3, `minCover: ${r(p.min_cover ?? null)},`);
  w(3, `maxCover: ${r(p.max_cover ?? null)},`);
  w(3, `harvestedOn: ${r(p.harvested_on)},`);
  w(3, `bands: ${r(p.bands)},`);
  w(3, `variants: {`);
  const slugs = new Set();
  for (const [vname, v] of Object.entries(p.variants)) {
    const slug = slugOf(vname);
    if (slugs.has(slug)) fail(`product ${pk}: variant slug "${slug}" collides (variant "${vname}")`);
    slugs.add(slug);
    w(4, `${key(slug)}: {`);
    w(5, `name: ${r(vname)},`);
    w(5, `maxIssueAnb: ${r(v.max_issue_anb ?? null)},`);
    w(5, `rates: {`);
    for (const [series, bands] of Object.entries(v.rates)) {
      w(6, `${key(series)}: {`);
      for (const [band, anbs] of Object.entries(bands)) {
        w(7, `${key(band)}: {`);
        for (const [anb, rate] of Object.entries(anbs)) {
          if (typeof rate !== "number" || !Number.isFinite(rate)) fail(`${pk}/${vname}/${series}/${band}/${anb}: rate is not a number`);
          w(8, `${key(anb)}: ${r(rate)},`);
          lines.push(rateLine(pk, slug, series, band, anb, rate));
          cellCount++;
        }
        w(7, `},`);
      }
      w(6, `},`);
    }
    w(5, `},`);
    w(4, `},`);
  }
  w(3, `},`);
  w(2, `},`);
  productBlocks.push(b.join("\n"));
}

const checksum = rateChecksum(lines);
const mr = (v, source = BOOK_SOURCE) => `row(${lit(v)}, "verified", ${lit(source)}, ${lit(newest)})`;
const modal = book.modal;

const out = [];
out.push(`/**
 * Tatil life rates, real-life-rates spec §5.2.
 *
 * This file is GENERATED by tools/import-life-rate-book.mjs from life-rate-book.json. Never hand-edit it.
 * To change a rate, re-run the script on a new book.
 * It is over the 800-line soft ceiling on purpose, because it is generated.
 */
import { row, deepFreeze } from "./row.ts";
import type { Row } from "./row.ts";

export interface LifeRateBand {
  readonly band: number;
  readonly from: number;
  readonly to: number | null;
}

export interface LifeRateVariant {
  /** The book's exact variant name. */
  readonly name: Row<string>;
  readonly maxIssueAnb: Row<number | null>;
  /** series ("F-NS" | "F-S" | "M-NS" | "M-S") -> band ("1" | "2" | "3") -> ANB -> rate per $1,000 a year. */
  readonly rates: Readonly<Record<string, Readonly<Record<string, Readonly<Record<string, Row<number>>>>>>>;
}

export interface LifeRateProduct {
  readonly name: Row<string>;
  readonly feeAnnual: Row<number>;
  readonly minPremiumAnnual: Row<number | null>;
  readonly minCover: Row<number | null>;
  readonly maxCover: Row<number | null>;
  readonly harvestedOn: Row<string>;
  readonly bands: Row<readonly LifeRateBand[]>;
  readonly variants: Readonly<Record<string, LifeRateVariant>>;
}

/** A cell the book lists as not harvested. */
export interface LifeRateMissing {
  readonly product: string;
  readonly variant: string;
  readonly series: string;
  readonly band: number;
  readonly anbs: readonly number[];
  readonly harvested: readonly number[];
}

/** A real quote kept out of the rate build. A dollar amount, NOT a rate per $1,000. */
export interface LifeRateHeldOut {
  readonly source: string;
  readonly note: string;
  readonly product: string;
  readonly variant: string;
  readonly series: string;
  readonly anb: number;
  readonly cover: number;
  readonly annual?: number;
  readonly semi?: number;
  readonly quarterly?: number;
  readonly monthly?: number;
}

export interface LifeRatesMeta {
  readonly ages: Row<string>;
  readonly feeAnnual: Row<number>;
  readonly modal: {
    readonly annual: Row<number>;
    readonly semi: Row<number>;
    readonly quarterly: Row<number>;
    readonly monthly: Row<number>;
  };
  readonly bookSchema: Row<number>;
  readonly cellCount: Row<number>;
  readonly checksum: Row<string>;
  readonly missing: Row<readonly LifeRateMissing[]>;
  readonly heldOut: Row<readonly LifeRateHeldOut[]>;
}

export interface LifeRates {
  readonly meta: LifeRatesMeta;
  readonly products: {
${PRODUCT_KEYS.map((k) => `    readonly ${k}: LifeRateProduct;`).join("\n")}
  };
}
`);
for (const pk of PRODUCT_KEYS) {
  out.push(`const SRC_${pk} = ${lit(sourceOf(pk, book.products[pk]))};`);
  out.push(`const ASOF_${pk} = ${lit(asOfOf[pk])};`);
}
out.push(`
export const LIFE_RATES: LifeRates = deepFreeze({
  meta: {
    ages: ${mr(book.ages)},
    feeAnnual: ${mr(book.fee_annual)},
    modal: {
      annual: ${mr(modal.annual)},
      semi: ${mr(modal.semi)},
      quarterly: ${mr(modal.quarterly)},
      monthly: ${mr(modal.monthly)},
    },
    bookSchema: ${mr(book.schema)},
    cellCount: ${mr(cellCount)},
    checksum: ${mr(checksum)},
    missing: ${mr(book.missing, `${BOOK_SOURCE}: cells the book lists as not harvested`)},
    heldOut: ${mr(book.held_out, `${BOOK_SOURCE}: held-out quotes (dollar amounts), not rates`)},
  },
  products: {
${productBlocks.join("\n")}
  },
});
`);

writeFileSync(OUT, out.join("\n"));
process.stdout.write(`cells ${cellCount}\nchecksum ${checksum}\nwrote ${OUT}\n`);
